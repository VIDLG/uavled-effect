import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const app = resolve(root, "../ledjs-ai");
const check = process.argv.includes("--check");
const sync = process.argv.includes("--sync");
const manifest = JSON.parse(await readFile(resolve(root, "manifest.json"), "utf8"));

async function output(relativePath, localPath, content) {
  const target = resolve(app, relativePath);
  if (check) {
    const actual = await readFile(target, "utf8");
    if (actual !== content) throw new Error(`${relativePath} differs from uavled-effects`);
  } else {
    const localTarget = resolve(root, "dist", localPath);
    await mkdir(dirname(localTarget), { recursive: true });
    await writeFile(localTarget, content, "utf8");
    if (sync) {
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, content, "utf8");
    }
  }
}

const prelude = (await Promise.all(manifest.prelude.map((path) => readFile(resolve(root, path), "utf8")))).join("");
await output("crates/uavled-protocol/lib/prelude.js", "prelude.js", prelude);

const files = new Map();
for (const path of new Set([...manifest.stylePresets, ...manifest.presets])) {
  files.set(path, JSON.parse(await readFile(resolve(root, path), "utf8")));
}
const registry = {
  schemaVersion: manifest.schemaVersion,
  stylePresets: manifest.stylePresets.map((path) => files.get(path).stylePreset),
  presets: manifest.presets.map((path) => files.get(path).preset),
};
await output("src/shared/effect-presets.json", "effect-presets.json", (JSON.stringify(registry, null, 2) + "\n").replaceAll("\n", "\r\n"));

const compact = [];
for (const entry of manifest.compact) {
  const source = await readFile(resolve(root, entry.path), "utf8");
  await output(`crates/uavled-protocol/lib/compact/${entry.path.slice('compact/'.length)}`, entry.path, source);
  compact.push(`        ${JSON.stringify(entry.id)} => Some(include_str!(${JSON.stringify(`../lib/compact/${entry.path.slice('compact/'.length)}`)})),`);
}
const rust = `// Generated by uavled-effects/scripts/build.mjs.\npub fn effect_library_source(id: &str) -> Option<&'static str> {\n    match id {\n${compact.join("\n")}\n        _ => None,\n    }\n}\n`;
await output("crates/uavled-protocol/src/effect_library_sources.rs", "effect_library_sources.rs", rust);
console.log(check ? "uavled-effects outputs match" : sync ? "uavled-effects outputs generated and synced" : "uavled-effects outputs generated in dist");
